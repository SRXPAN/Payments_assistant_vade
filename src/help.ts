// Тексты справки: что видит человек по кнопке «❓ Помощь» и при выдаче доступа.
import type { Role } from "./db";
import { OVERDUE_DAYS } from "./reminders";

export function helpText(role: Role, warnDays: number): string {
  const parts: string[] = [
    "❓ Как пользоваться ботом",
    "Бот хранит список платежей клуба и напоминает, когда подходит срок оплаты.",
    [
      "📋 Список — все платежи, ближайшие сверху. Дата в строке — до какого числа оплачено.",
      `🟢 — до срока больше ${warnDays} дн. (у платежа может быть свой запас)`,
      "🟡 — пора платить",
      "🔴 — просрочено",
      "⚠️ вых. / праздник — срок выпадает на день, когда банки не работают. Платить нужно до указанного рабочего дня, и дни считаются от него.",
      "💳 авто — деньги списываются с карты сами.",
      "Под списком — кнопка «🏷 По категориям», если категории заданы.",
    ].join("\n"),
    "🔎 Поиск — просто напишите боту часть названия платежа.",
  ];

  if (role === "viewer") {
    parts.push("Ваша роль — наблюдатель: вы видите список, но не меняете платежи.");
    return parts.join("\n\n");
  }

  parts.push(
    [
      "➕ Добавить — три шага: название, дата «оплачено до», как часто платится. Дату можно писать 25.11.2026, 25.11.26 или просто 25.11.",
      "«📋 Добавить списком» — сразу несколько платежей: по строке на платёж, «Название; дата; период».",
    ].join("\n"),
    [
      "✏️ Изменить — выберите платёж, откроется карточка:",
      "• ✅ Оплатил — срок сдвигается на следующий период; разовый платёж уходит в архив",
      "• 📅 +1 месяц / квартал / год — если оплатили на другой срок, чем обычно",
      "• ↩️ Отменить оплату — если нажали по ошибке",
      "• ✏️ Изменить дату, 🔤 Переименовать, 🗑 Удалить",
      "• 📝 Заметка — где платить, номер договора; видна в напоминании",
      "• ⚙️ Параметры — период, время и запас дней для напоминания, ответственный, автосписание, категория",
    ].join("\n"),
    [
      "🔔 Напоминания приходят в рабочую группу:",
      `• каждый день начиная за ${warnDays} дн. до срока (или за свой запас платежа) и в день срока`,
      `• ещё ${OVERDUE_DAYS} дн. после срока`,
      "• в понедельник — план на неделю и список давно просроченных",
      "Если у платежа есть ответственный, бот упоминает его в напоминании.",
      "Под напоминанием можно сразу нажать ✅ Оплатил, 📅 +1 мес или ✏️ Дата.",
    ].join("\n"),
    "💳 Автосписание (в параметрах платежа) — для подписок, которые сами снимают деньги с карты: бот напомнит проверить баланс, а после даты сам сдвинет срок.",
  );

  parts.push(
    [
      "⚙️ Настройки — за сколько дней предупреждать, время проверки, выходные, рабочая группа.",
      "• 🧪 Проверить сейчас — прислать сегодняшние напоминания ещё раз",
      "• 📤 Экспорт CSV — платежи и журнал для Excel",
      "• 🗑 Корзина — вернуть удалённый или архивный платёж",
      "Если в группе включены темы — упомяните бота (@имя_бота) в нужной теме, и он будет писать туда.",
    ].join("\n"),
  );

  if (role === "owner") {
    parts.push(
      [
        "👥 Доступ — кто пользуется ботом. Новый человек нажимает Start, владельцам приходит запрос. Роль можно сменить или забрать в любой момент.",
        "• 👑 Владелец — всё, включая доступ; владельцев может быть несколько",
        "• Админ — платежи и настройки, но не доступ",
        "• Наблюдатель — только список и поиск",
      ].join("\n"),
      "Чтобы напоминания шли в группу, добавьте бота в неё сами — он запомнит группу.",
      "Владельцам приходят: запросы доступа, уведомления об удалении платежа и ручной смене срока админом, а по понедельникам — резервная копия (CSV).",
    );
  }
  return parts.join("\n\n");
}

/** Сообщение в группу при привязке — его удобно закрепить. */
export function groupHelp(botUsername: string): string {
  return [
    "Готово, буду напоминать здесь.",
    "",
    "ℹ️ Как это работает",
    "Каждый день я пишу сюда о платежах, у которых подходит срок, — отдельное сообщение на каждый платёж. Если срок выпадает на выходной или праздник, считаю от последнего рабочего дня перед ним. По понедельникам присылаю план на неделю.",
    "",
    "Кнопки под напоминанием:",
    "✅ Оплатил — отметить оплату, срок сдвинется на следующий период",
    "📅 +1 мес — оплатили на месяц вперёд",
    "✏️ Дата — указать другую дату: я попрошу ответить на моё сообщение",
    "↩️ Отменить оплату — появляется после отметки, если нажали по ошибке",
    "",
    "Нажимать кнопки могут владелец и админы, остальным бот ответит «Нет доступа».",
    "Добавлять и менять платежи — в личном чате со мной.",
    "",
    `Если в группе включены темы: владелец пишет @${botUsername} в нужной теме — и я буду писать туда.`,
    "📌 Закрепите это сообщение, чтобы оно не потерялось.",
  ].join("\n");
}
